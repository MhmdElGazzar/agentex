#!/usr/bin/env node
'use strict';
// Architecture map: the README's "How it fits together" diagrams, generated from the repo so
// they can never go stale. Maintainer tooling — never shipped (scripts/hosts/build_host.js
// COMMON_EXCLUDES drops scripts/dev); the README block it writes does ship.
//
//   node scripts/dev/architecture.js --check    exit 1 when the README block is out of date
//   node scripts/dev/architecture.js --write    rewrite the block in place
//   node scripts/dev/architecture.js --print    print the generated block, write nothing
//   [--root <dir>]   the plugin repo root (default: this repo)
//
// What it reads:
//   - commands/*.md; skills/<name>/SKILL.md (a folder without one is not a skill); agents/*.md
//   - a link X → skill S: X names `skills/S/` or "**S** skill" (a skill also counts its
//     references/**/*.md)
//   - a link X → agent A: X names `A` in backticks (or as `agents/A.md`)
// What it writes, between the two markers in README.md:
//   1. "What you run, and what it uses" — commands → skills → agents; skills no command
//      reaches are grouped as triggered by spec steps or other skills
//   2. "Which skill relies on which" — skill → skill
//
// Output: ONE JSON line on stdout {ok, mode, stale?, commands, skills, agents, links}.
// Exit 0 ok · 1 --check found the block stale or missing · 2 usage or repo error.
const fs = require('node:fs');
const path = require('node:path');

const BEGIN = '<!-- agentex:architecture:begin (generated by scripts/dev/architecture.js --write; do not edit) -->';
const END = '<!-- agentex:architecture:end -->';

function emit(o, code) { process.stdout.write(JSON.stringify(o) + '\n'); process.exit(code); }

function parseArgs(argv) {
  const a = { mode: null, root: path.resolve(__dirname, '..', '..') };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (k === '--check' || k === '--write' || k === '--print') {
      if (a.mode) emit({ ok: false, error: 'pass exactly one of --check, --write, --print' }, 2);
      a.mode = k.slice(2);
    } else if (k === '--root' && argv[i + 1]) a.root = path.resolve(argv[++i]);
    else emit({ ok: false, error: `unknown argument "${k}". usage: architecture.js --check|--write|--print [--root <dir>]` }, 2);
  }
  if (!a.mode) emit({ ok: false, error: 'pass one of --check, --write, --print' }, 2);
  return a;
}

const listMd = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.md')).map((f) => f.slice(0, -3)).sort() : []);
const read = (f) => fs.readFileSync(f, 'utf8');

// The repo's parts and the links between them.
function scan(root) {
  const skillsDir = path.join(root, 'skills');
  const skills = fs.existsSync(skillsDir)
    ? fs.readdirSync(skillsDir).filter((d) => fs.existsSync(path.join(skillsDir, d, 'SKILL.md'))).sort()
    : [];
  const commands = listMd(path.join(root, 'commands'));
  const agents = listMd(path.join(root, 'agents'));

  const skillText = (s) => {
    const dir = path.join(skillsDir, s);
    const refs = path.join(dir, 'references');
    const files = [path.join(dir, 'SKILL.md')];
    if (fs.existsSync(refs)) {
      for (const f of fs.readdirSync(refs, { recursive: true })) if (String(f).endsWith('.md')) files.push(path.join(refs, String(f)));
    }
    return files.sort().map(read).join('\n');
  };
  const skillRefs = (text, self) => {
    const found = new Set();
    for (const m of text.matchAll(/skills\/([a-z0-9-]+)\//g)) found.add(m[1]);
    for (const m of text.matchAll(/\*\*([a-z0-9-]+)\*\* skill/g)) found.add(m[1]);
    return [...found].filter((s) => skills.includes(s) && s !== self).sort();
  };
  const agentRefs = (text) => agents.filter((a) => text.includes('`' + a + '`') || text.includes(`agents/${a}.md`));

  const cmdSkill = []; const cmdAgent = []; const skillSkill = []; const skillAgent = [];
  for (const c of commands) {
    const t = read(path.join(root, 'commands', c + '.md'));
    for (const s of skillRefs(t)) cmdSkill.push([c, s]);
    for (const a of agentRefs(t)) cmdAgent.push([c, a]);
  }
  for (const s of skills) {
    const t = skillText(s);
    for (const o of skillRefs(t, s)) skillSkill.push([s, o]);
    for (const a of agentRefs(t)) skillAgent.push([s, a]);
  }
  return { commands, skills, agents, cmdSkill, cmdAgent, skillSkill, skillAgent };
}

const nodeId = (prefix, name) => prefix + '_' + name.replace(/[^a-z0-9]/gi, '_');

function render(m) {
  const fromCommand = new Set(m.cmdSkill.map(([, s]) => s));
  const direct = m.skills.filter((s) => fromCommand.has(s));
  const indirect = m.skills.filter((s) => !fromCommand.has(s));
  const L = [];
  L.push(BEGIN, '', '### What you run, and what it uses', '');
  L.push(`${m.commands.length} commands, ${m.skills.length} skills and ${m.agents.length} subagents. Solid arrows: a command runs a skill. Dotted arrows: work handed to a subagent.`, '');
  L.push('```mermaid', 'flowchart LR');
  L.push('  subgraph CMD["Commands you type"]');
  for (const c of m.commands) L.push(`    ${nodeId('c', c)}["/${c}"]`);
  L.push('  end');
  L.push('  subgraph SK["Skills a command runs"]');
  for (const s of direct) L.push(`    ${nodeId('s', s)}["${s}"]`);
  L.push('  end');
  if (indirect.length) {
    L.push('  subgraph SK2["Skills triggered by spec steps or other skills"]');
    for (const s of indirect) L.push(`    ${nodeId('s', s)}["${s}"]`);
    L.push('  end');
  }
  if (m.agents.length) {
    L.push('  subgraph AG["Subagents (parallel runs)"]');
    for (const a of m.agents) L.push(`    ${nodeId('a', a)}(["${a}"])`);
    L.push('  end');
  }
  for (const [c, s] of m.cmdSkill) L.push(`  ${nodeId('c', c)} --> ${nodeId('s', s)}`);
  const handed = new Set();
  for (const [s, a] of m.skillAgent) { handed.add(a + ':' + s); L.push(`  ${nodeId('s', s)} -.-> ${nodeId('a', a)}`); }
  for (const [c, a] of m.cmdAgent) {
    // A command that hands work to an agent its skill already hands it to adds no new line.
    const viaSkill = m.cmdSkill.some(([cc, s]) => cc === c && handed.has(a + ':' + s));
    if (!viaSkill) L.push(`  ${nodeId('c', c)} -.-> ${nodeId('a', a)}`);
  }
  L.push('```', '');
  L.push('### Which skill relies on which', '');
  L.push('An arrow means the skill reads the other skill\'s instructions or runs its scripts. Arrows both ways mark two skills that depend on each other.', '');
  L.push('```mermaid', 'flowchart LR');
  const linked = new Set(m.skillSkill.flat());
  for (const s of m.skills.filter((x) => linked.has(x))) L.push(`  ${nodeId('s', s)}["${s}"]`);
  for (const [a, b] of m.skillSkill) L.push(`  ${nodeId('s', a)} --> ${nodeId('s', b)}`);
  L.push('```', '', END);
  return L.join('\n');
}

function current(readme) {
  const b = readme.indexOf(BEGIN); const e = readme.indexOf(END);
  return b === -1 || e === -1 || e < b ? null : readme.slice(b, e + END.length);
}

function main() {
  const a = parseArgs(process.argv.slice(2));
  const readmePath = path.join(a.root, 'README.md');
  if (!fs.existsSync(readmePath)) emit({ ok: false, error: `no README.md under ${a.root}` }, 2);
  const m = scan(a.root);
  const block = render(m);
  const counts = { commands: m.commands.length, skills: m.skills.length, agents: m.agents.length,
    links: m.cmdSkill.length + m.cmdAgent.length + m.skillSkill.length + m.skillAgent.length };
  if (a.mode === 'print') { process.stdout.write(block + '\n'); return; }
  const readme = read(readmePath);
  const have = current(readme);
  if (a.mode === 'check') {
    if (have === block) emit({ ok: true, mode: 'check', stale: false, ...counts }, 0);
    emit({ ok: false, mode: 'check', stale: true, missing: have === null, ...counts,
      fix: 'run: node scripts/dev/architecture.js --write' }, 1);
  }
  if (have === null) emit({ ok: false, error: `README.md has no ${END.slice(5, 31)} markers; add the begin/end lines where the map belongs` }, 2);
  if (have !== block) fs.writeFileSync(readmePath, readme.replace(have, block));
  emit({ ok: true, mode: 'write', changed: have !== block, ...counts }, 0);
}

if (require.main === module) main();
module.exports = { scan, render, BEGIN, END };
